#!/usr/bin/env python3
"""Build the dashboard's timezone table, client/device/timezones.ts.

Every IANA name the installed tzdata resolves, with the POSIX TZ string ESPHome
compiles for `timezone: <name>`: the dashboard sends that string to the device, so
a zone set from the page runs exactly as the same zone set in YAML. The zones the
picker lists are zone.tab's, each with its country, and UTC; every other name is
kept so that a browser reporting an old alias (Europe/Kiev) still finds its zone.

Usage:
    scripts/build-timezones.py            # regenerate the table
    scripts/build-timezones.py --check    # fail if the table is stale
"""

from __future__ import annotations

import argparse
from importlib import resources
from pathlib import Path
import sys

from esphome.components.time import validate_tz
import tzdata

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT = (
    REPO_ROOT
    / "components"
    / "web_device_dashboard"
    / "client"
    / "device"
    / "timezones.ts"
)

# The device refuses a longer zone name or POSIX string.
MAX_BYTES = 63


def tab_rows(name: str) -> list[list[str]]:
    text = (resources.files("tzdata.zoneinfo") / name).read_text(encoding="utf-8")
    return [line.split("\t") for line in text.splitlines() if not line.startswith("#")]


def link_targets() -> dict[str, str]:
    """Each link name's zone, from tzdata.zi's `L target link` lines."""
    zi = (resources.files("tzdata.zoneinfo") / "tzdata.zi").read_text()
    links = {}
    for line in zi.splitlines():
        if line.startswith("L "):
            _, target, link = line.split()
            links[link] = target
    return links


def ts_str(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def build() -> str:
    names = sorted((resources.files("tzdata") / "zones").read_text().split())
    posix = {name: validate_tz(name) for name in names}
    for name, value in posix.items():
        if not value or max(len(name.encode()), len(value.encode())) > MAX_BYTES:
            raise SystemExit(f"{name} ({value!r}): empty, or over {MAX_BYTES} bytes")

    countries = dict(row[:2] for row in tab_rows("iso3166.tab"))
    zone_country = {row[2]: row[0] for row in tab_rows("zone.tab")}
    zone_country["UTC"] = ""
    listed = sorted(zone_country)

    # A name is the same zone as a listed one when both end at one tzdata zone.
    links = link_targets()

    def final(name: str) -> str:
        while name in links:
            name = links[name]
        return name

    by_target: dict[str, str] = {}
    for name in listed:
        by_target.setdefault(final(name), name)
    for name in listed:
        by_target[name] = name

    strings = sorted(set(posix.values()), key=lambda s: (len(s), s))
    index = {value: i for i, value in enumerate(strings)}
    listed_index = {name: i for i, name in enumerate(listed)}
    aliases, others = [], []
    for name in names:
        if name in zone_country:
            continue
        same = by_target.get(final(name))
        if same is not None and posix[same] == posix[name]:
            aliases.append((name, listed_index[same]))
        else:
            others.append((name, index[posix[name]]))

    used = sorted({code for code in zone_country.values() if code})
    lines = [
        f"// Generated by scripts/build-timezones.py from tzdata {tzdata.IANA_VERSION}"
        " - do not edit.",
        "// Each IANA name with the POSIX TZ string ESPHome compiles for"
        " `timezone: <name>`.",
        "",
        "/** The tzdata release the table comes from. */",
        f"export const TZDATA_VERSION = {ts_str(tzdata.IANA_VERSION)}",
        "",
        "/** The POSIX TZ strings, each once; the tables below index into it. */",
        "export const TZ_POSIX: readonly string[] = [",
        *(f"  {ts_str(value)}," for value in strings),
        "]",
        "",
        "/** iso3166.tab's English country names, by ISO 3166 code. */",
        "export const TZ_COUNTRIES: Readonly<Record<string, string>> = {",
        *(f"  {code}: {ts_str(countries[code])}," for code in used),
        "}",
        "",
        "/** The zones a picker lists, zone.tab's and UTC: name, POSIX string index,"
        " country code ('' for UTC). */",
        "export const TZ_LISTED: ReadonlyArray<readonly [string, number, string]> = [",
        *(
            f"  [{ts_str(name)}, {index[posix[name]]}, {ts_str(zone_country[name])}],"
            for name in listed
        ),
        "]",
        "",
        "/** Names that are a listed zone under another name: name, TZ_LISTED index. */",
        "export const TZ_ALIASES: ReadonlyArray<readonly [string, number]> = [",
        *(f"  [{ts_str(name)}, {i}]," for name, i in aliases),
        "]",
        "",
        "/** The rest, no listed zone's equal: name, POSIX string index. */",
        "export const TZ_OTHERS: ReadonlyArray<readonly [string, number]> = [",
        *(f"  [{ts_str(name)}, {i}]," for name, i in others),
        "]",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the generated file is up to date instead of writing it",
    )
    args = parser.parse_args()

    contents = build()
    target = OUT.relative_to(REPO_ROOT)
    if args.check:
        if (OUT.read_text() if OUT.is_file() else None) != contents:
            print(
                f"out of date: {target}\nRun scripts/build-timezones.py and commit it."
            )
            return 1
        print(f"{target} is up to date")
        return 0
    OUT.write_text(contents)
    print(f"  wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
