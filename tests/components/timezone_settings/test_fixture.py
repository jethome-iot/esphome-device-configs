"""posix_tz_cases.tsv is what Python's parser says: the C++ suite is only as good as that."""

from importlib import metadata
import re
import unittest

import generate_fixture

LINES = generate_fixture.FIXTURE.read_text().splitlines()
HEADER = re.match(
    r"# Generated by generate_fixture.py from tzdata (\S+) and aioesphomeapi (\S+);",
    LINES[0],
)
ROWS = [line.split("\t") for line in LINES if line and not line.startswith("#")]
REGENERATE = "run python tests/components/timezone_settings/generate_fixture.py"


class Fixture(unittest.TestCase):
    def test_every_row_is_what_python_makes_of_its_string(self):
        for fields in ROWS:
            kind, label, posix = fields[:3]
            with self.subTest(posix=posix):
                self.assertEqual(fields, generate_fixture.row(kind, label, posix))

    def test_the_odd_strings_parse_and_the_malformed_do_not(self):
        verdicts = {(fields[0], fields[3]) for fields in ROWS}
        self.assertIn(("odd", "ok"), verdicts)
        self.assertIn(("malformed", "error"), verdicts)
        self.assertNotIn(("odd", "error"), verdicts)
        self.assertNotIn(("malformed", "ok"), verdicts)
        self.assertNotIn(("zone", "error"), verdicts)

    def test_the_malformed_are_ascii(self):
        # The device refuses anything else before parsing; the C++ suite covers that apart.
        for posix in generate_fixture.MALFORMED + generate_fixture.ODD:
            self.assertTrue(all(" " <= c <= "~" for c in posix), posix)

    def test_it_lists_every_zone_of_the_installed_tzdata(self):
        self.assertIsNotNone(HEADER, LINES[0])
        made_with = HEADER.group(1)
        installed = metadata.version("tzdata")
        if made_with != installed:
            self.skipTest(
                f"the fixture is from tzdata {made_with}, {installed} is installed: "
                f"{REGENERATE}"
            )
        self.assertEqual(
            generate_fixture.FIXTURE.read_text(),
            generate_fixture.render(),
            f"out of date: {REGENERATE}",
        )


if __name__ == "__main__":
    unittest.main()
