RULE_FIELDS = ("type", "month", "week", "day_of_week", "day", "time_seconds")


def _rule(rule):
    return [str(int(getattr(rule, field))) for field in RULE_FIELDS]


def row(kind, label, posix):
    """kind, label, posix, then `error`, or `ok` and the struct's fields."""
    try:
        parsed = parse_posix_tz(posix)
    except ValueError:
        return [kind, label, posix, "error"]
    return [
        kind,
        label,
        posix,
        "ok",
        str(parsed.std_offset_seconds),
        str(parsed.dst_offset_seconds),
        *_rule(parsed.dst_start),
        *_rule(parsed.dst_end),
    ]


def zones():
    """Every zone tzdata lists, links included, and the POSIX string time's validator gives it."""
    names = (
        resources.files("tzdata").joinpath("zones").read_text(encoding="utf-8").split()
    )
    return [
        (name, time_._extract_tz_string(time_._load_tzdata(name))) for name in names
    ]


def header():
    tzdata = metadata.version("tzdata")
    api = metadata.version("aioesphomeapi")
    return [
        f"# Generated by generate_fixture.py from tzdata {tzdata} and aioesphomeapi {api}; do not edit.",
        "# kind\tlabel\tposix\tverdict\tstd\tdst\t"
        + "\t".join(f"start_{f}" for f in RULE_FIELDS)
        + "\t"
        + "\t".join(f"end_{f}" for f in RULE_FIELDS),
    ]


def rows():
    out = [row("zone", name, posix) for name, posix in zones()]
    out += [row("odd", "-", posix) for posix in ODD]
    out += [row("malformed", "-", posix) for posix in MALFORMED]
    out += [row("stricter", "-", posix) for posix in STRICTER]
    return out


def render():
    return "\n".join(header() + ["\t".join(fields) for fields in rows()]) + "\n"


def main():
    FIXTURE.write_text(render(), encoding="utf-8")
    print(f"wrote {FIXTURE}")


if __name__ == "__main__":
    main()
