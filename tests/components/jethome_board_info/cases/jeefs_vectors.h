// Where the writer puts device.id today: header, its file header, then the record. The walker
// no longer assumes it, so this lives here rather than in the parser.
constexpr uint16_t DEVICE_ID_ADDR = BOARD_DATA_SIZE + FILE_HEADER_SIZE;
static_assert(FILE_HEADER_ADDR == 256);
static_assert(DEVICE_ID_ADDR == 284);

// Every multi-byte JEEFS field is little-endian, so the builders write bytes, not structs.
inline void put_u16(uint8_t *raw, size_t off, uint16_t value) {
  raw[off] = static_cast<uint8_t>(value & 0xFF);
  raw[off + 1] = static_cast<uint8_t>(value >> 8);
}

inline void put_u32(uint8_t *raw, size_t off, uint32_t value) {
  for (size_t i = 0; i < 4; i++) {
    raw[off + i] = static_cast<uint8_t>((value >> (8 * i)) & 0xFF);
  }
}

inline uint32_t get_u32(const uint8_t *raw, size_t off) {
  uint32_t value = 0;
  for (size_t i = 0; i < 4; i++) {
    value |= static_cast<uint32_t>(raw[off + i]) << (8 * i);
  }
  return value;
}

// Bounded string: as many bytes as fit, no NUL forced, the rest left zero.
inline void put_field(uint8_t *raw, size_t off, size_t len, const std::string &value) {
  const size_t n = value.size() < len ? value.size() : len;
  memcpy(raw + off, value.data(), n);
}

inline void seal_header(HeaderBuf &buf) {
  put_u32(buf.data(), HDR_OFF_CRC32, compute_crc32(buf.data(), CRC_DATA_SIZE));
}

inline void seal_file_header(FileHeaderBuf &buf) {
  put_u32(buf.data(), FH_OFF_HEADER_CRC32, compute_crc32(buf.data(), FILE_HEADER_CRC_DATA_SIZE));
}

inline void seal_record(RecordBuf &buf) {
  put_u32(buf.data(), REC_OFF_CRC32, compute_crc32(buf.data(), DEVICE_ID_CRC_DATA_SIZE));
}

// Field values mirror the upstream v4_header_minimal vector, except the USID, which upstream
// leaves 16 chars and the serial cross-check needs at v2's 30.
inline HeaderBuf make_header(uint8_t version = HEADER_VERSION_V4) {
  HeaderBuf buf{};
  memcpy(buf.data() + HDR_OFF_MAGIC, BOARD_MAGIC, sizeof(BOARD_MAGIC));
  buf[HDR_OFF_VERSION] = version;
  buf[HDR_OFF_SIG_VERSION] = SIG_NONE;
  buf[HDR_OFF_FS_VERSION] = FS_VERSION_JEEFS_V1;
  put_field(buf.data(), HDR_OFF_BOARDNAME, 32, "JetHub-D2");
  put_field(buf.data(), HDR_OFF_BOARDVERSION, 32, "2.1");
  put_field(buf.data(), HDR_OFF_BOARD_SERIAL, 32, "BS-2026-00001");
  put_field(buf.data(), HDR_OFF_USID, 32, "JXD6E101002601012026000042ABCD");
  put_field(buf.data(), HDR_OFF_CPUID, 32, "F0:57:8D:10:20:30");
  const uint8_t mac[6] = {0xF0, 0x57, 0x8D, 0x10, 0x20, 0x30};
  memcpy(buf.data() + HDR_OFF_MAC, mac, sizeof(mac));
  seal_header(buf);
  return buf;
}

// `next` defaults to 0, the terminator — a chained header gets it from make_image().
inline FileHeaderBuf make_file_header(const std::string &name, uint16_t data_size, uint32_t data_crc,
                                      uint16_t next = 0) {
  FileHeaderBuf buf{};
  put_field(buf.data(), FH_OFF_NAME, 16, name);
  put_u16(buf.data(), FH_OFF_DATA_SIZE, data_size);
  put_u32(buf.data(), FH_OFF_CRC32, data_crc);
  put_u16(buf.data(), FH_OFF_NEXT, next);
  seal_file_header(buf);
  return buf;
}

inline RecordBuf make_record(uint8_t record_version = DEVID_RECORD_VERSION, uint8_t signature_version = SIG_NONE) {
  RecordBuf buf{};
  memcpy(buf.data() + REC_OFF_MAGIC, DEVID_MAGIC, sizeof(DEVID_MAGIC));
  buf[REC_OFF_RECORD_VERSION] = record_version;
  buf[REC_OFF_SIG_VERSION] = signature_version;
  put_field(buf.data(), REC_OFF_DEVICE_MODEL, 32, "JetHub-D2");
  put_field(buf.data(), REC_OFF_DEVICE_SERIAL, 32, "DSN-2026-000042");
  put_field(buf.data(), REC_OFF_HW_REVISION, 16, "1.2a");
  seal_record(buf);
  return buf;
}

// What the JEEFS file header must carry for a record: the CRC over all 256 data bytes.
inline uint32_t file_data_crc_of(const RecordBuf &record) { return compute_crc32(record.data(), DEVICE_ID_SIZE); }

struct FileSpec {
  std::string name;
  std::vector<uint8_t> data;
};

// Lays a board header and a contiguous chain into one image, linking each header to the next.
inline std::vector<uint8_t> make_image(const std::vector<FileSpec> &files, size_t image_size = 8192,
                                       uint8_t fs_version = FS_VERSION_JEEFS_V1) {
  std::vector<uint8_t> image(image_size, 0);
  HeaderBuf header = make_header();
  header[HDR_OFF_FS_VERSION] = fs_version;
  seal_header(header);
  memcpy(image.data(), header.data(), header.size());

  size_t at = FILE_HEADER_ADDR;
  for (size_t i = 0; i < files.size(); i++) {
    const std::vector<uint8_t> &data = files[i].data;
    const size_t end = at + FILE_HEADER_SIZE + data.size();
    const uint16_t next = i + 1 < files.size() ? static_cast<uint16_t>(end) : 0;
    FileHeaderBuf fh = make_file_header(files[i].name, static_cast<uint16_t>(data.size()),
                                        compute_crc32(data.data(), data.size()), next);
    memcpy(image.data() + at, fh.data(), fh.size());
    memcpy(image.data() + at + FILE_HEADER_SIZE, data.data(), data.size());
    at = end;
  }
  return image;
}

// The record as a file, so a chain can be built around the real device.id bytes.
inline FileSpec device_id_file(const RecordBuf &record) {
  return FileSpec{DEVICE_ID_NAME, std::vector<uint8_t>(record.begin(), record.end())};
}

// Drives a walk over an image the way the component drives it over I2C.
inline JeefsWalk walk_image(const std::vector<uint8_t> &image, const char *name) {
  JeefsWalk walk{};
  walk_begin(&walk, image[HDR_OFF_FS_VERSION], static_cast<uint32_t>(image.size()), name);
  uint16_t at = 0;
  while (walk_want(&walk, &at)) {
    walk_feed(&walk, image.data() + at);
  }
  return walk;
}

