inline void put_i16(uint8_t *raw, size_t off, int16_t value) { put_u16(raw, off, static_cast<uint16_t>(value)); }

inline void put_i64(uint8_t *raw, size_t off, int64_t value) {
  const auto bits = static_cast<uint64_t>(value);
  put_u32(raw, off, static_cast<uint32_t>(bits & 0xFFFFFFFF));
  put_u32(raw, off + 4, static_cast<uint32_t>(bits >> 32));
}

inline void seal_meter_record(MeterRecordBuf &buf) {
  put_u32(buf.data(), MC_OFF_CRC32, jethome_board_info::compute_crc32(buf.data(), RECORD_CRC_DATA_SIZE));
}

// The PM3-3 rev 1.2 board the ATM90E32 records are written for, and the PM1-6 rev 1.1.0 one.
struct BoardIdentity {
  const char *model;
  const char *revision;
  const char *serial;
};
constexpr BoardIdentity PM33{"JXD-D3-PM3-3", "1.2", "PM33-2026-000123"};
constexpr BoardIdentity PM16{"JXD-D3-PM1-6", "1.1.0", "PM16-2026-000045"};
constexpr int64_t CALIBRATED_AT = 1791288000;  // 2026-10-06 12:00:00 UTC

// The same values the Python builder writes, so make_meter_record() of either chip equals its
// vector byte for byte.
inline MeterRecordBuf make_meter_record(ChipType chip = ChipType::ATM90E32) {
  const bool atm = chip == ChipType::ATM90E32;
  const BoardIdentity &board = atm ? PM33 : PM16;
  MeterRecordBuf buf{};
  memcpy(buf.data() + MC_OFF_MAGIC, RECORD_MAGIC, RECORD_MAGIC_SIZE);
  buf[MC_OFF_RECORD_VERSION] = RECORD_VERSION;
  buf[MC_OFF_SIG_VERSION] = SIGNATURE_NONE;
  buf[MC_OFF_CHIP_TYPE] = static_cast<uint8_t>(chip);
  buf[MC_OFF_CHANNEL_COUNT] = atm ? 3 : 6;
  put_field(buf.data(), MC_OFF_BOARD_MODEL, 32, board.model);
  put_field(buf.data(), MC_OFF_BOARD_REVISION, 8, board.revision);
  put_field(buf.data(), MC_OFF_BOARD_SERIAL, 32, board.serial);
  put_u32(buf.data(), MC_OFF_REF_VOLTAGE, 230000);
  put_u32(buf.data(), MC_OFF_REF_CURRENT, 5000);
  put_u16(buf.data(), MC_OFF_CT_RATIO, 2000);
  buf[MC_OFF_LINE_FREQ] = 50;
  buf[MC_OFF_PGA] = atm ? 0x15 : 0x00;
  put_i16(buf.data(), MC_OFF_AMBIENT, 235);
  put_u16(buf.data(), MC_OFF_FLAGS, 0x003F);
  put_field(buf.data(), MC_OFF_STATION, 12, "ST-01");
  put_field(buf.data(), MC_OFF_REF_INSTRUMENT, 16, "REF-6305-0042");
  if (atm) {
    const int32_t phases[3][8] = {
        {39470, 31600, -12, 7, 3, -4, -150, 0x8012},
        {39391, 31702, 0, 0, 0, 0, 0, 0x0000},
        {39555, 31511, 5, -3, -1, 2, 88, 0x0007},
    };
    for (size_t p = 0; p < 3; p++) {
      uint8_t *at = buf.data() + ATM_OFF_PHASE + p * ATM_PHASE_SIZE;
      for (size_t i = 0; i < 8; i++)
        put_u16(at, 2 * i, static_cast<uint16_t>(phases[p][i]));
    }
    buf[ATM_OFF_CURRENT_SCALE] = 2;
    put_u32(buf.data(), ATM_OFF_PLCONST, 0);
  } else {
    const uint32_t ki[6] = {59856000, 59901000, 59811000, 59870000, 59840000, 59866000};
    const uint32_t kp[6] = {214100000, 214250000, 213990000, 214120000, 214080000, 214160000};
    const int16_t phase[6] = {120, -80, 0, 35, -15, 60};
    const uint16_t i_off[6] = {20, 18, 22, 19, 21, 20};
    const int16_t p_off[6] = {5, -3, 0, 2, -1, 4};
    const int16_t err[6] = {45, 52, 38, 60, 41, 49};
    put_u32(buf.data(), BL_OFF_KV, 14998000);
    for (size_t c = 0; c < 6; c++) {
      put_u32(buf.data(), BL_OFF_KI + 4 * c, ki[c]);
      put_u32(buf.data(), BL_OFF_KP + 4 * c, kp[c]);
      put_i16(buf.data(), BL_OFF_PHASE + 2 * c, phase[c]);
      put_u16(buf.data(), BL_OFF_I_OFF + 2 * c, i_off[c]);
      put_i16(buf.data(), BL_OFF_P_OFF + 2 * c, p_off[c]);
      put_i16(buf.data(), BL_OFF_ERR_WORST + 2 * c, err[c]);
    }
  }
  put_i64(buf.data(), MC_OFF_TIMESTAMP, CALIBRATED_AT);
  put_u32(buf.data(), MC_OFF_OPERATOR, 7);
  seal_meter_record(buf);
  return buf;
}

